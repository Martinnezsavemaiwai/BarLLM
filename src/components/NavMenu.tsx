interface NavMenuProps {
  labels: { openClaude: string; settings: string; checkUpdates: string; exit: string };
  onOpenClaude?: () => void;
  onSettings?: () => void;
  onUpdate?: () => void;
  onExit?: () => void;
}

/**
 * Sidebar navigation items for the Click Panel.
 */
export function NavMenu({ labels, onOpenClaude, onSettings, onUpdate, onExit }: NavMenuProps) {
  const items = [
    { label: labels.openClaude, icon: ExternalIcon, onClick: onOpenClaude },
    { label: labels.settings, icon: SettingsIcon, onClick: onSettings },
    { label: labels.checkUpdates, icon: UpdateIcon, onClick: onUpdate },
    { label: labels.exit, icon: ExitIcon, onClick: onExit, danger: true },
  ];

  return (
    <nav className="flex flex-col gap-0.5">
      {items.map((item) => (
        <button
          key={item.label}
          onClick={item.onClick}
          className="flex items-center gap-2.5 px-3 py-2 rounded-lg text-xs transition-colors cursor-pointer text-left w-full"
          style={{
            color: item.danger ? "var(--color-status-critical)" : "var(--color-text-secondary)",
          }}
          onMouseEnter={(e) => {
            (e.currentTarget as HTMLElement).style.background = "var(--color-bg-elevated)";
          }}
          onMouseLeave={(e) => {
            (e.currentTarget as HTMLElement).style.background = "transparent";
          }}
        >
          <item.icon size={14} />
          {item.label}
        </button>
      ))}
    </nav>
  );
}

